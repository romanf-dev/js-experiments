    async function fillMem(addr, sz, dword) {
        const len = sz / 4;
        for (let i = 0; i < len; ++i)
            await write(addr + (i << 2), dword); 
    }

    async function copyMem(addr, sz, dwords) {
        const len = sz / 4;
        for (let i = 0; i < len; ++i)
            await write(addr + (i << 2), dwords[i]); 
    }

